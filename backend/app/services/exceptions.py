"""Исключения сервисного слоя. Роутеры ловят их и переводят в HTTP-ответы —
сам сервис ничего не знает про FastAPI/HTTPException."""


class NotFoundError(Exception):
    """Сущность не найдена (заявка, место и т.д.)."""


class ValidationConflictError(Exception):
    """Операция логически невозможна (например, ручной выбор нарушает жёсткое условие)."""
